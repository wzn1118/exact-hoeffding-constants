#!/usr/bin/env python3
"""Generate the public-theorem audit for the actual umbrella import closure."""
from pathlib import Path
import argparse
import re

ROOT = Path(__file__).resolve().parents[1]


def uncomment(text):
    """Remove nested Lean comments while preserving declaration line breaks."""
    out, depth, i, quoted = [], 0, 0, False
    while i < len(text):
        pair = text[i:i + 2]
        c = text[i]
        if depth:
            if pair == '/-':
                depth += 1
                i += 2
            elif pair == '-/':
                depth -= 1
                i += 2
            else:
                out.append('\n' if c == '\n' else ' ')
                i += 1
        elif quoted:
            out.append(c)
            if c == '\\' and i + 1 < len(text):
                out.append(text[i + 1])
                i += 2
            else:
                if c == '"':
                    quoted = False
                i += 1
        elif pair == '/-':
            depth = 1
            i += 2
        elif pair == '--':
            end = text.find('\n', i)
            i = len(text) if end < 0 else end
        else:
            if c == '"':
                quoted = True
            out.append(c)
            i += 1
    if depth or quoted:
        raise ValueError('Unclosed comment or string')
    return ''.join(out)


def generate():
    seen, declarations = set(), []

    def visit(module):
        if module in seen or not module.startswith('ExactHoeffding'):
            return
        seen.add(module)
        path = ROOT / (module.replace('.', '/') + '.lean')
        source = uncomment(path.read_text())
        for imported in re.findall(r'^import\s+(\S+)', source, re.M):
            visit(imported)
        if module != 'ExactHoeffding':
            for name in re.findall(r'^(?:@\[[^\n]*\]\s*)?(?:protected\s+)?'
                                   r'(?:theorem|lemma)\s+([^\s(:{]+)', source, re.M):
                declarations.append(('ExactHoeffding.' + name, path.relative_to(ROOT)))

    visit('ExactHoeffding')
    names = [name for name, _ in declarations]
    if len(names) != len(set(names)):
        raise ValueError('Duplicate public theorem names')
    output = ['import ExactHoeffding', '',
              '-- Generated by checks/generate_axiom_audit.py; do not edit by hand.',
              f'-- {len(names)} public theorems in {len(seen) - 1} imported project modules.', '']
    for name, _ in declarations:
        output.append('#print axioms ' + name)
    return '\n'.join(output) + '\n', len(names), len(seen) - 1


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated, count, modules = generate()
    destination = ROOT / 'checks/full_closure_axioms.lean'
    if args.check:
        if destination.read_text() != generated:
            raise SystemExit('Axiom audit is out of date; regenerate it')
    else:
        destination.write_text(generated)
    print(f'Public theorem audit: {count} declarations, {modules} modules')
